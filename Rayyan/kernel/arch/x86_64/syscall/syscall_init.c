#include <stdint.h>

/*
 * Temporary GDT selector values.
 *
 * Assumed GDT layout:
 *
 *   Index 0 -> Null
 *   Index 1 -> Kernel Code (Ring 0)
 *   Index 2 -> Kernel Data (Ring 0)
 *   Index 3 -> User Code   (Ring 3)
 *   Index 4 -> User Data   (Ring 3)
 *
 * These values will be replaced/verified when the real GDT
 * implementation is added.
 */

 /*
    These are all arbitrary values generated by GPT. Later these values will changed
    by the actual values.
 */
#define KERNEL_CS 0x08
#define KERNEL_DS 0x10
#define USER_CS   0x18
#define USER_DS   0x20

#define IA32_STAR   0xC0000081
#define IA32_LSTAR  0xC0000082
#define IA32_FMASK  0xC0000084

extern void syscall_entry(void);

static inline void wrmsr(uint32_t msr, uint64_t value)
{
    uint32_t low = (uint32_t)value;
    uint32_t high = (uint32_t)(value >> 32);

    asm volatile (
        "wrmsr"
        :
        : "c"(msr),
          "a"(low),
          "d"(high)
        : "memory"
    );
}

void syscall_init(void)
{
    /*
     * LSTAR:
     *
     * Address of the kernel entry point for SYSCALL.
     */
    wrmsr(IA32_LSTAR, (uint64_t)syscall_entry);

    /*
     * FMASK:
     *
     * Clear IF (Interrupt Flag) when entering the kernel.
     * 
     * prevents any maskable hardware interrupt from interrupting the 
     * CPU as it enters the the syscall handler.
     */
    wrmsr(IA32_FMASK, (1ULL << 9));

    /*
     * STAR:
     *
     * Bits 47:32 -> kernel CS
     * Bits 63:48 -> user CS base
     * 
     * and a bitwise or is done to fill the values at the designated positions in STAR, 
     * as 0 to 31 are reserved 
     *
     * The CPU derives the corresponding SS values
     * from these selectors.
     *
     * Temporary values based on our assumed GDT.
     */
    uint64_t star =
        ((uint64_t)(USER_CS) << 48) |
        ((uint64_t)(KERNEL_CS) << 32);

    wrmsr(IA32_STAR, star);
}